// Front-end equivalents of the qualified FMSH MMCM/global/IO clock primitives.
// JFM's installed 030ai adaptation and factory implementation remain required.
module hdmi_clock_jfm
    #(parameter integer MODE_720P = 0)
    (input wire ref_100m,
        input wire reset,
        output wire pixel_clk,
        output wire serial_clk,
        output wire locked);
    wire feedback_raw, feedback, serial_raw;
    MMCME2_BASE #(.BANDWIDTH("OPTIMIZED"),
        .CLKIN1_PERIOD(10.0),
        .CLKFBOUT_MULT_F(37.125),
        .DIVCLK_DIVIDE(5),
        // 保持原 VCO 与参考时钟；720p 仅将串行输出再除 2，得到 371.25/74.25MHz。
        .CLKOUT0_DIVIDE_F(MODE_720P ? 2.0 : 1.0),
        .STARTUP_WAIT("FALSE"))
        mmcm(.CLKIN1(ref_100m),
            .CLKFBIN(feedback),
            .CLKFBOUT(feedback_raw),
            .CLKOUT0(serial_raw),
            .LOCKED(locked),
            .PWRDWN(1'b0),
            .RST(reset));
    BUFG feedback_buffer(.I(feedback_raw),
             .O(feedback));
    // Same fast source and the supported BUFIO/BUFR pair preserve the
    // serialization relationship. CLKDIV is generated by the regional /5.
    BUFR #(.BUFR_DIVIDE("5"),
        .SIM_DEVICE("7SERIES"))
        pixel_buffer(.I(serial_raw),
            .O(pixel_clk),
            .CE(1'b1),
            .CLR(!locked));
    BUFIO serial_buffer(.I(serial_raw),
              .O(serial_clk));
endmodule
